log = get_logger(__name__)

#: How many suffixed names to try when a branch already exists, before giving
#: up. Never force-push over the existing one: it may be someone else's work.
_MAX_BRANCH_ATTEMPTS = 5


def _issue_number(run: Run) -> str | None:
    """Issue number from the URL the user supplied, never from issue prose."""
    if not run.issue_url:
        return None
    match = re.search(r"/issues/(\d+)", run.issue_url)
    return match.group(1) if match else None


def commit_message(run: Run, version: PatchVersionRow) -> str:
    """A deterministic commit message. No model call.

    Attribution is explicit: the commit says PatchPilot generated the change and
    that a human approved it. It never claims a person authored code they did
    not write.
    """
    number = _issue_number(run)
    subject = (run.issue_title or "").strip().splitlines()[0] if run.issue_title else ""
    if number:
        headline = f"fix: resolve issue #{number}"
    elif subject:
        headline = f"fix: {subject[:60]}"
    else:
        headline = f"fix: patch generated for run {run.code}"

    body = [
        "",
        f"Generated by PatchPilot (run {run.code}, patch v{version.version}).",
        f"Model: {version.model or run.model}.",
        "Reviewed and approved by a human before publication.",
    ]
    return headline + "\n" + "\n".join(body) + "\n"


def pull_request_body(run: Run, version: PatchVersionRow, publication: PublicationRow) -> str:
    """PR description assembled from what the run already recorded.

    No second model call: everything here was produced during the repair.
    """
    verification = version.verification or {}
    number = _issue_number(run)

    lines: list[str] = ["## Summary", ""]
    if number:
        lines.append(f"PatchPilot investigated issue #{number} and generated this repair.")
    else:
        lines.append("PatchPilot investigated the reported issue and generated this repair.")
    lines.append("")

    if version.root_cause:
        lines += ["## Root cause", "", version.root_cause.strip(), ""]
    if version.repair_summary:
        lines += ["## Changes", "", version.repair_summary.strip(), ""]
    if version.files:
        lines += [""] + [f"- `{path}`" for path in version.files[:25]] + [""]

    lines += ["## Verification", ""]
    if verification.get("summary_recognized"):
        lines += [
            f"- {verification.get('passed', 0)} passed, {verification.get('failed', 0)} failed, "
            f"{verification.get('errors', 0)} errors",
            f"- Framework: {verification.get('framework', 'unknown')}",
            "- Test output recognised: yes",
        ]
    else:
        lines.append(
            "- The runner's summary was not machine-recognised; see the run for raw output."
        )
    lines.append("")

    lines += [
        "## PatchPilot",
        "",
        f"- Run: `{run.code}`",
        f"- Patch version: {version.version}",
        f"- Model: {version.model or run.model}",
        f"- Approved patch SHA-256: `{version.digest[:16]}…`",
        f"- Base: `{publication.base_commit_sha[:12]}` on `{publication.base_branch}`",
        "",
        "A human reviewed and approved this exact patch before the branch was published.",
        "PatchPilot does not merge; this pull request follows your normal review process.",
    ]
    if publication.base_drifted:
        lines += [
            "",
            f"> Note: `{publication.base_branch}` moved while the agent was working. "
            "This branch is based on the commit the patch was reviewed against, so the "
            "approved content is unchanged; resolve any conflicts as usual.",
        ]
    return "\n".join(lines)


def pull_request_title(run: Run) -> str:
    number = _issue_number(run)
    subject = (run.issue_title or "").strip().splitlines()[0] if run.issue_title else ""
    if subject and number:
        return f"fix: {subject[:70]} (#{number})"
    if subject:
        return f"fix: {subject[:70]}"
    if number:
        return f"fix: resolve issue #{number}"
    return f"fix: PatchPilot repair for run {run.code}"


class PublicationService:
    """Drives one publication. Holds no state beyond the injected port."""

    def __init__(
        self,
        host: GitHostingPort,
        settings: Settings | None = None,
    ) -> None:
        self.host = host
        self.settings = settings or get_settings()

    # -- helpers ------------------------------------------------------------
    async def _record(
        self,
        session: AsyncSession,
        publication: PublicationRow,
        step: PublicationStep,
        **fields: Any,
    ) -> None:
        steps = list(publication.completed_steps or [])
        if str(step) not in steps:
            steps.append(str(step))
        publication.completed_steps = steps
        publication.updated_at = datetime.now(UTC)
        for key, value in fields.items():
            setattr(publication, key, value)

    async def _fail(
        self,
        session: AsyncSession,
        run: Run,
        publication: PublicationRow,
        code: PublishErrorCode,
        message: str,
    ) -> PublicationRow:
        publication.state = str(ReviewState.PUBLISH_FAILED)
        publication.error_code = str(code)
        publication.error_detail = message[:2000]
        publication.updated_at = datetime.now(UTC)
        run.review_state = str(
            ensure_transition(ReviewState(run.review_state), ReviewState.PUBLISH_FAILED)
        )
        await review_service.record_audit(
            session,
            run,
            ReviewAction.PUBLISH_FAILED,
            version=None,
            digest=publication.patch_digest,
            detail={"code": str(code), "message": message[:500],
                    "completed_steps": list(publication.completed_steps or [])},
        )
        log.warning("publish.failed", run_id=run.id, code=str(code))
        return publication

    async def existing(self, session: AsyncSession, run: Run) -> PublicationRow | None:
        """The publication for the currently approved patch, if any."""
        if not run.approved_patch_sha256:
            return (
                await session.execute(
                    sa.select(PublicationRow)
                    .where(PublicationRow.run_id == run.id)
                    .order_by(PublicationRow.id.desc())
                    .limit(1)
                )
            ).scalars().first()
        return (
            await session.execute(
                sa.select(PublicationRow).where(
                    PublicationRow.run_id == run.id,
                    PublicationRow.patch_digest == run.approved_patch_sha256,
                )
            )
        ).scalars().first()

    # -- the workflow -------------------------------------------------------
    async def publish(
        self, session: AsyncSession, run: Run, *, actor: str | None = None
    ) -> PublicationRow:
        """Publish the approved patch, or resume a partially completed attempt.

        Idempotent by construction: the publication row is keyed on
        ``(run_id, patch_digest)``, so a second call finds the first attempt and
        continues it rather than creating a second branch or pull request.
        """
        version = await review_service.approved_version(session, run)
        digest = run.approved_patch_sha256 or ""

        publication = await self.existing(session, run)
        if publication is not None and publication.pr_number:
            # Already finished. Return what exists rather than doing it twice.
            log.info("publish.already_done", run_id=run.id, pr=publication.pr_number)
            return publication

        identity = self._identity(run)
        if publication is None:
            publication = PublicationRow(
                run_id=run.id,
                patch_version_id=version.id,
                patch_digest=digest,
                state=str(ReviewState.PUBLISHING),
                provider="github",
                owner=identity.owner if identity else "",
                repo=identity.repo if identity else "",
                base_commit_sha=run.base_commit or "",
                base_branch=run.base_branch or "",
            )
            session.add(publication)
            await session.flush()

        publication.state = str(ReviewState.PUBLISHING)
        publication.error_code = None
        publication.error_detail = None
        if ReviewState(run.review_state) is not ReviewState.PUBLISHING:
            run.review_state = str(
                ensure_transition(ReviewState(run.review_state), ReviewState.PUBLISHING)
            )
        await review_service.record_audit(
            session, run, ReviewAction.PUBLISH_STARTED, version=version.version,
            actor=actor, digest=digest,
        )

        try:
            return await self._run_steps(session, run, publication, version, identity, actor)
        except GitHostingError as exc:
            return await self._fail(session, run, publication, exc.code, str(exc))
        except Exception as exc:
            log.exception("publish.unexpected", run_id=run.id)
            return await self._fail(
                session, run, publication, PublishErrorCode.UNKNOWN, f"{type(exc).__name__}: {exc}"
            )

    def _identity(self, run: Run) -> RepositoryIdentity | None:
        if run.repo_owner and run.repo_name:
            return RepositoryIdentity(
                provider=run.repo_provider or "github",
                owner=run.repo_owner,
                repo=run.repo_name,
            )
        return parse_repository(run.repo_url)

    async def _run_steps(
        self,
        session: AsyncSession,
        run: Run,
        publication: PublicationRow,
        version: PatchVersionRow,
        identity: RepositoryIdentity | None,
        actor: str | None,
    ) -> PublicationRow:
        # 1. The patch must still be exactly what was approved.
        if patch_digest(version.diff) != publication.patch_digest:
            return await self._fail(
                session, run, publication, PublishErrorCode.PATCH_DIGEST_MISMATCH,
                "The stored patch no longer matches the approved digest. "
                "Nothing was published; the patch must be approved again.",
            )
        await self._record(session, publication, PublicationStep.VERIFIED_DIGEST)

        # 2. Where does it go?
        if not self.host.configured:
            return await self._fail(
                session, run, publication, PublishErrorCode.NOT_CONFIGURED,
                "GitHub integration is not configured.",
            )
        if identity is None:
            return await self._fail(
                session, run, publication, PublishErrorCode.REPOSITORY_UNKNOWN,
                "This run has no GitHub repository recorded, so there is nowhere "
                "to publish. Runs from a local path cannot be published.",
            )
        if not run.base_commit:
            return await self._fail(
                session, run, publication, PublishErrorCode.BASE_COMMIT_UNKNOWN,
                "This run did not record the base commit it was prepared from, so "
                "the patch cannot be applied to a known revision.",
            )

        repository = await self.host.get_repository(identity.owner, identity.repo)
        base_branch = publication.base_branch or run.base_branch or repository.default_branch
        publication.owner = identity.owner
        publication.repo = identity.repo
        publication.base_branch = base_branch
        publication.base_commit_sha = run.base_commit
        await self._record(session, publication, PublicationStep.RESOLVED_REPOSITORY)

        # 2b. Direct or fork? Decided from the credential's permissions, before
        #     anything is written. A retry that already resolved a fork reuses
        #     the recorded one rather than asking GitHub again.
        try:
            target = await self._target(publication, identity)
        except GitHostingError as exc:
            return await self._fail(session, run, publication, exc.code, str(exc))
        publication.strategy = str(target.strategy)
        publication.head_owner = target.head_owner
        publication.head_repo = target.head_repo
        await self._record(session, publication, PublicationStep.SELECTED_STRATEGY)
        if target.is_fork:
            await self._record(session, publication, PublicationStep.RESOLVED_FORK)
            log.info(
                "publish.strategy",
                run_id=run.id, strategy=str(target.strategy),
                head=f"{target.head_owner}/{target.head_repo}",
                upstream=f"{target.upstream_owner}/{target.upstream_repo}",
            )

        # 3. Base drift. We do not rebase and we do not rewrite the patch: the
        #    branch is cut from the commit the patch was reviewed against, so
        #    approved content stays byte-identical. Drift is recorded, surfaced
        #    in the UI and noted in the PR, and GitHub shows any conflict.
        head = await self.host.get_branch_head(identity.owner, identity.repo, base_branch)
        drifted = bool(head and head != run.base_commit)
        publication.observed_base_head = head
        publication.base_drifted = drifted
        if drifted:
            log.info(
                "publish.base_drifted", run_id=run.id,
                approved_base=run.base_commit[:12], current_head=head[:12],
            )
        await self._record(session, publication, PublicationStep.CHECKED_DRIFT)

        # 4. A branch we are allowed to write.
        branch = publication.branch or await self._free_branch(run, target)
        # Guarded against the default branch of whichever repository is being
        # written to -- upstream's for direct, the fork's own for a fork.
        ensure_pushable(branch, default_branch=target.head_default_branch)
        ensure_pushable(branch, default_branch=target.upstream_default_branch)
        publication.branch = branch

        # 5. Apply, verify, commit, push. The adapter re-derives the diff after
        #    applying and refuses to push if it differs from the approved bytes.
        if not publication.has_completed(str(PublicationStep.BRANCH_PUSHED)):
            commit_sha = await self.host.push_branch(
                owner=target.head_owner,
                repo=target.head_repo,
                branch=branch,
                base_commit_sha=run.base_commit,
                patch=version.diff,
                commit_message=commit_message(run, version),
                author_name=self.settings.github_commit_author_name,
                author_email=self.settings.github_commit_author_email,
                source_owner=target.upstream_owner,
                source_repo=target.upstream_repo,
                protected_default_branch=target.head_default_branch,
            )
            await self._record(
                session, publication, PublicationStep.APPLIED_PATCH
            )
            await self._record(session, publication, PublicationStep.VERIFIED_APPLIED_DIFF)
            await self._record(
                session, publication, PublicationStep.COMMIT_CREATED, commit_sha=commit_sha
            )
            await self._record(session, publication, PublicationStep.BRANCH_PUSHED)
            await review_service.record_audit(
                session, run, ReviewAction.BRANCH_CREATED, version=version.version,
                actor=actor, digest=publication.patch_digest,
                detail={"branch": branch, "base": run.base_commit},
            )
            await review_service.record_audit(
                session, run, ReviewAction.COMMIT_CREATED, version=version.version,
                actor=actor, detail={"commit": commit_sha},
            )
            await review_service.record_audit(
                session, run, ReviewAction.BRANCH_PUSHED, version=version.version,
                actor=actor, detail={"branch": branch},
            )

        # 6. The pull request. Adopt an existing one if a previous attempt got
        #    this far but lost the response.
        head_ref = target.head_ref(branch)
        existing_pr = await self.host.find_pull_request(
            owner=target.upstream_owner, repo=target.upstream_repo, head=head_ref
        )
        pull = existing_pr or await self.host.create_pull_request(
            # Always upstream, never the fork: a fork-to-fork pull request would
            # be invisible to the maintainers the change is meant for.
            owner=target.upstream_owner,
            repo=target.upstream_repo,
            head=head_ref,
            base=base_branch,
            title=pull_request_title(run),
            body=pull_request_body(run, version, publication),
            draft=self.settings.github_pr_draft,
        )
        await self._record(
            session,
            publication,
            PublicationStep.PR_CREATED,
            pr_number=pull.number,
            pr_url=pull.url,
            pr_state=pull.state,
            state=str(ReviewState.PR_CREATED),
        )
        run.review_state = str(
            ensure_transition(ReviewState(run.review_state), ReviewState.PR_CREATED)
        )
        await review_service.record_audit(
            session, run, ReviewAction.PR_CREATED, version=version.version, actor=actor,
            digest=publication.patch_digest,
            detail={"pr_number": pull.number, "pr_url": pull.url, "branch": branch},
        )
        log.info("publish.pr_created", run_id=run.id, pr=pull.number, branch=branch)
        return publication

    async def _target(
        self, publication: PublicationRow, identity: RepositoryIdentity
    ) -> PublicationTarget:
        """Where this publication writes, reusing what a previous attempt found.

        Re-deciding on every retry would ask GitHub to fork again after a
        failure between the fork call and the push. The recorded head is
        authoritative once it exists.
        """
        recorded = publication.head_owner and publication.head_repo
        if recorded and publication.has_completed(str(PublicationStep.SELECTED_STRATEGY)):
            strategy = PublicationStrategy(publication.strategy or str(PublicationStrategy.DIRECT))
            upstream = await self.host.get_repository(identity.owner, identity.repo)
            head_default = upstream.default_branch
            if strategy is PublicationStrategy.FORK:
                fork = await self.host.get_repository(
                    str(publication.head_owner), str(publication.head_repo)
                )
                head_default = fork.default_branch
            return PublicationTarget(
                strategy=strategy,
                upstream_owner=identity.owner,
                upstream_repo=identity.repo,
                upstream_default_branch=upstream.default_branch,
                head_owner=str(publication.head_owner),
                head_repo=str(publication.head_repo),
                head_default_branch=head_default,
            )
        return await select_target(self.host, owner=identity.owner, repo=identity.repo)

    async def _free_branch(self, run: Run, target: PublicationTarget) -> str:
        """A branch name that does not already exist in the head repository.

        Suffixes on collision instead of reusing or force-pushing: an existing
        branch of the same name may be an earlier publication whose PR is still
        open, or unrelated work.
        """
        base = branch_name(
            run_id=run.id, issue_number=_issue_number(run), title=run.issue_title
        )
        for attempt in range(_MAX_BRANCH_ATTEMPTS):
            candidate = collision_name(base, attempt)
            if not await self.host.branch_exists(
                target.head_owner, target.head_repo, candidate
            ):
                return candidate
        raise GitHostingError(
            PublishErrorCode.BRANCH_EXISTS,
            f"Branches named {base} (and {_MAX_BRANCH_ATTEMPTS - 1} suffixed variants) "
            "already exist. Delete or rename them, then retry.",
        )

    # -- read-only ----------------------------------------------------------
    async def refresh_status(
        self, session: AsyncSession, publication: PublicationRow
    ) -> PublicationRow:
        """Refresh PR state and CI checks. Never merges, never re-pushes."""
        if not (publication.pr_number and publication.owner and self.host.configured):
            return publication
        try:
            pull = await self.host.get_pull_request(
                owner=publication.owner, repo=publication.repo, number=publication.pr_number
            )
            publication.pr_state = pull.state
            if publication.commit_sha:
                checks = await self.host.get_check_runs(
                    owner=publication.owner, repo=publication.repo, ref=publication.commit_sha
                )
                publication.checks = {
                    "runs": [
                        {"name": c.name, "status": c.status, "conclusion": c.conclusion,
                         "url": c.url}
                        for c in checks
                    ],
                    "fetched_at": datetime.now(UTC).isoformat(),
                }
            publication.updated_at = datetime.now(UTC)
        except GitHostingError as exc:
            log.info("publish.status_refresh_failed", code=str(exc.code))
        return publication


def build_service(settings: Settings | None = None) -> PublicationService:
    settings = settings or get_settings()
    return PublicationService(GitHubAdapter(settings), settings)
